package cn.edu.meowmap

import cn.edu.meowmap.data.*
import cn.edu.meowmap.ui.MapPoint
import cn.edu.meowmap.ui.toAmapGeometry
import cn.edu.meowmap.ui.toAmapLatLng
import cn.edu.meowmap.ui.toWgsMapPoint
import com.google.gson.JsonObject
import com.google.gson.JsonParser
import org.junit.Assert.*
import org.junit.Test
import java.io.ByteArrayOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class OriginalMigrationTest {
    @Test fun desktopCoordinateRoundTripPreservesCampusPoint() {
        val gcj = Coordinates.toGcj(23.0507, 113.4033)
        // Fixture generated by the original desktop's utils.wgs84ToGcj02.
        assertEquals(23.0481730922355, gcj.first, 0.00000001)
        assertEquals(113.40881938117761, gcj.second, 0.00000001)
        assertTrue(Coordinates.meters(23.0507, 113.4033, gcj.first, gcj.second) > 100)
        val gps = Coordinates.toWgs(gcj.first, gcj.second)
        assertEquals(23.0507, gps.first, 0.0000001)
        assertEquals(113.4033, gps.second, 0.0000001)
        assertEquals(51.5 to -0.1, Coordinates.toGcj(51.5, -0.1))
    }
    @Test fun nativeMapUsesDesktopCoordinatesAndConvertsClicksBackToWgs84() {
        val originalLat = 23.0481730922355
        val originalLng = 113.40881938117761
        val payload = JsonObject().apply {
            addProperty("id", "campus")
            addProperty("user_id", "alice")
            addProperty("lat", originalLat)
            addProperty("lng", originalLng)
        }
        val record = cloudRecord(payload)
        val position = MapPoint(record.latitude, record.longitude)
        val camera = position.toAmapLatLng()
        val overlay = position.toAmapGeometry()
        val picked = camera.toWgsMapPoint()

        assertEquals(originalLat, camera.latitude, 1e-8)
        assertEquals(originalLng, camera.longitude, 1e-8)
        assertEquals(originalLat, overlay.latitude(), 1e-8)
        assertEquals(originalLng, overlay.longitude(), 1e-8)
        assertEquals(23.0507, picked.latitude, 1e-8)
        assertEquals(113.4033, picked.longitude, 1e-8)
    }

    @Test fun publicIdentityIncludesAuthorAndKeepsCatAssociation() {
        val first = JsonParser.parseString("""{"id":"same","user_id":"alice","lat":23.05,"lng":113.4,"cat_id":"cat-1","created_at":"2026-11-03T00:00:00.000Z"}""").asJsonObject
        val second = first.deepCopy().apply { addProperty("user_id", "bob") }
        assertNotEquals(cloudRecord(first).id, cloudRecord(second).id)
        assertEquals("cat-1", cloudRecord(first).catId)
        assertEquals("alice", cloudRecord(first).userId)
    }
    @Test fun desktopLocalTimesUseChinaTimezone() {
        assertEquals(originalTime("2026-11-03T00:00:00Z"), originalTime("2026-11-03T08:00"))
    }
    @Test fun portableBackupIncludesPhotoBytes() {
        val payload = JsonObject().apply { addProperty("app", "meow-meow-map") }
        val name = "photos/12345678-1234-1234-1234-123456789abc"
        val (restored, photos) = PortableBackup.decode(PortableBackup.encode(payload, mapOf(name to byteArrayOf(1, 2, 3))))
        assertEquals(payload, restored)
        assertArrayEquals(byteArrayOf(1, 2, 3), photos[name])
    }
    @Test(expected = IllegalArgumentException::class) fun archiveRejectsUnexpectedPaths() {
        val bytes = ByteArrayOutputStream()
        ZipOutputStream(bytes).use { it.putNextEntry(ZipEntry("../credential")); it.write(byteArrayOf(1)); it.closeEntry() }
        PortableBackup.decode(bytes.toByteArray())
    }
}
